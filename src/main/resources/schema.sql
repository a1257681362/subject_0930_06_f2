-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- F1 风电叶片巡检台账
-- 归属口径：风机服役窗口、叶片归属窗口统一为左闭右开 [起, 止)。
-- ============================================================

-- 风机档案：场址、机型、并网时间
CREATE TABLE IF NOT EXISTS t_turbine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_no VARCHAR(64) NOT NULL,
    site VARCHAR(128) NOT NULL,
    model VARCHAR(64) NOT NULL,
    grid_connected_at TIMESTAMP NOT NULL,
    decommissioned_at TIMESTAMP NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_SERVICE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_turbine_no UNIQUE (turbine_no)
);

-- 叶片档案：序列号、方位、材料；installed_at/removed_at 构成归属窗口 [installed_at, removed_at)
CREATE TABLE IF NOT EXISTS t_blade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blade_no VARCHAR(64) NOT NULL,
    serial_no VARCHAR(64) NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    material VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    installed_at TIMESTAMP NOT NULL,
    removed_at TIMESTAMP NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_SERVICE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_blade_no UNIQUE (blade_no),
    CONSTRAINT uk_blade_serial_no UNIQUE (serial_no)
);

-- 换件记录：保留旧件与新件的前后关系
CREATE TABLE IF NOT EXISTS t_blade_replacement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_id BIGINT NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    old_blade_id BIGINT NOT NULL,
    new_blade_id BIGINT NOT NULL,
    replaced_at TIMESTAMP NOT NULL,
    reason VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 巡检工单：关联无人机影像；状态 PENDING/INSPECTED/DEFECT_REGISTERED/REPAIRED/ACCEPTED/CLOSED
CREATE TABLE IF NOT EXISTS t_inspection_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    blade_id BIGINT NULL,
    inspect_time TIMESTAMP NULL,
    drone_image_url VARCHAR(512) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_inspection_order_no UNIQUE (order_no)
);

-- 缺陷登记：缺陷等级、维修结果、验收结论
CREATE TABLE IF NOT EXISTS t_defect (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    blade_id BIGINT NOT NULL,
    defect_level VARCHAR(16) NOT NULL,
    description VARCHAR(512) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    repair_result VARCHAR(512) NULL,
    repaired_at TIMESTAMP NULL,
    accepted_at TIMESTAMP NULL,
    accept_remark VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-1', 'F1 风电叶片巡检台账：风机/叶片/换件/巡检工单/缺陷');

-- ============================================================
-- F2 无人机叶片巡检航线
-- 航线按风机、叶片方位、拍摄距离配置；版本化发布、发布前三校验、
-- 审批（半程停留待处理）、临时改线留版本差异；历史影像继续引用原航线版本。
-- ============================================================

-- 巡检工单绑定飞行时使用的航线版本；影像提交后冻结，历史影像可追溯原航线
ALTER TABLE t_inspection_order ADD COLUMN IF NOT EXISTS route_version_id BIGINT NULL;
ALTER TABLE t_inspection_order ADD COLUMN IF NOT EXISTS route_mission_id BIGINT NULL;
ALTER TABLE t_inspection_order ADD COLUMN IF NOT EXISTS route_change_apply_id BIGINT NULL;

-- 航线：一条风机一条叶片巡检航线（按航点表达叶片方位与拍摄距离）
CREATE TABLE IF NOT EXISTS t_flight_route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_no VARCHAR(64) NOT NULL,
    route_name VARCHAR(128) NOT NULL,
    turbine_id BIGINT NOT NULL,
    -- 气象/电量作业阈值随航线配置，发布时据此校验
    max_wind_speed DOUBLE NOT NULL DEFAULT 10.0,
    reserve_battery_pct INT NOT NULL DEFAULT 30,
    estimated_power_pct INT NOT NULL DEFAULT 60,
    current_version_id BIGINT NULL,
    remark VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_flight_route_no UNIQUE (route_no)
);

-- 航线版本：每次发布/改线生成不可变快照，版本差异行存 t_route_version_diff
CREATE TABLE IF NOT EXISTS t_flight_route_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    version_no VARCHAR(32) NOT NULL,
    base_version_id BIGINT NULL,
    change_type VARCHAR(24) NOT NULL,
    -- 航点配置快照（JSON），保证历史版本永远可还原、可追溯
    waypoint_snapshot CLOB NOT NULL,
    snapshot_hash VARCHAR(64) NOT NULL,
    max_wind_speed DOUBLE NOT NULL,
    reserve_battery_pct INT NOT NULL,
    estimated_power_pct INT NOT NULL,
    -- DRAFT 草稿 / PUBLISHED 发布 / ARCHIVED 被新版本取代
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMP NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_route_version_no UNIQUE (route_id, version_no)
);

-- 航点：风机 + 叶片方位 + 拍摄距离（米）的具体巡拍位置
CREATE TABLE IF NOT EXISTS t_route_waypoint (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    seq INT NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    shoot_distance_m DOUBLE NOT NULL,
    longitude DOUBLE NOT NULL,
    latitude DOUBLE NOT NULL,
    altitude_m DOUBLE NOT NULL DEFAULT 80.0,
    gimbal_pitch_deg DOUBLE NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_route_waypoint_seq UNIQUE (route_id, seq)
);

-- 版本差异：临时改线必须经审批，并逐行保留与基线版本的差异
CREATE TABLE IF NOT EXISTS t_route_version_diff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    change_kind VARCHAR(16) NOT NULL,
    seq INT NULL,
    blade_position VARCHAR(8) NULL,
    field_name VARCHAR(32) NOT NULL,
    old_value VARCHAR(255) NULL,
    new_value VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 临时禁飞区：圆形区域，生效窗口左闭右开 [start_time, end_time)
CREATE TABLE IF NOT EXISTS t_no_fly_zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_no VARCHAR(64) NOT NULL,
    zone_name VARCHAR(128) NOT NULL,
    zone_type VARCHAR(16) NOT NULL DEFAULT 'TEMPORARY',
    longitude DOUBLE NOT NULL,
    latitude DOUBLE NOT NULL,
    radius_m DOUBLE NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NULL,
    reason VARCHAR(255) NULL,
    -- ACTIVE 生效中 / REVOKED 已撤销
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_no_fly_zone_no UNIQUE (zone_no)
);

-- 发布前校验结果：禁飞区/风速/电量，禁飞区冲突记录坐标与原因；航线规划可追溯
CREATE TABLE IF NOT EXISTS t_route_publish_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    passed BOOLEAN NOT NULL,
    checked_at TIMESTAMP NOT NULL,
    wind_speed DOUBLE NULL,
    max_wind_speed DOUBLE NULL,
    battery_pct INT NULL,
    reserve_battery_pct INT NULL,
    -- 冲突明细 JSON：[{zoneNo,zoneName,longitude,latitude,radiusM,waypointSeq,bladePosition,distanceM,reason}]
    conflict_detail CLOB NULL,
    fail_reasons CLOB NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 审批单：航线发布 / 临时改线；两级审批，只完成一半时停留 PENDING_HALF
CREATE TABLE IF NOT EXISTS t_route_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_no VARCHAR(64) NOT NULL,
    route_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    approval_type VARCHAR(24) NOT NULL,
    base_version_id BIGINT NULL,
    reason VARCHAR(255) NULL,
    -- PENDING 待一审（0/2）/ PENDING_HALF 待处理（一级已通过，只完成一半）/ APPROVED / REJECTED
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    first_approver VARCHAR(64) NULL,
    first_approved_at TIMESTAMP NULL,
    first_remark VARCHAR(255) NULL,
    final_approver VARCHAR(64) NULL,
    final_approved_at TIMESTAMP NULL,
    final_remark VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_route_approval_no UNIQUE (approval_no)
);

-- 飞行任务：待起飞/飞行中/已完成；起飞后绑定版本冻结，新版本只重绑未起飞任务
CREATE TABLE IF NOT EXISTS t_flight_mission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_no VARCHAR(64) NOT NULL,
    route_id BIGINT NOT NULL,
    route_version_id BIGINT NOT NULL,
    turbine_id BIGINT NOT NULL,
    -- PENDING 未起飞 / FLYING 飞行中 / FINISHED 已完成 / CANCELLED
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    scheduled_at TIMESTAMP NULL,
    departed_at TIMESTAMP NULL,
    finished_at TIMESTAMP NULL,
    -- 最近一次发布前/起飞前校验结果，未起飞任务在新版本发布时重算
    last_check_id BIGINT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_flight_mission_no UNIQUE (mission_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f2-1', 'F2 无人机叶片巡检航线：航线版本化、禁飞区/风速/电量发布校验、两级审批、飞行任务绑定');
